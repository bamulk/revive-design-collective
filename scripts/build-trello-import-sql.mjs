// Reads ~/Downloads/trello-export.json, emits scripts/trello-import.sql.
// Re-runnable: clients dedup on (name, imported_from='trello'),
// stages dedup on trello_card_id.

import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';

const EXPORT = path.join(os.homedir(), 'Downloads', 'trello-export.json');
const OUT = decodeURIComponent(new URL('./trello-import.sql', import.meta.url).pathname);

const LIST_TO_STATUS = {
  'Upcoming Stages': 'scheduled',
  'Scheduled Stages': 'scheduled',
  'Current Stages': 'staged',
  'Destages': 'destaged',
  'Completed': 'paid',
};

const sqlString = (s) => {
  if (s == null) return 'null';
  return `'${String(s).replace(/'/g, "''")}'`;
};
const sqlNumber = (n) => (n == null || Number.isNaN(Number(n)) ? 'null' : String(Number(n)));
const sqlBool = (b) => (b ? 'true' : 'false');
const sqlDate = (d) => (d ? sqlString(d.slice(0, 10)) : 'null');

const data = JSON.parse(fs.readFileSync(EXPORT, 'utf8'));
const listsById = Object.fromEntries(data.lists.map(l => [l.id, l]));
const cfs = Object.fromEntries(data.customFields.map(f => [f.id, f]));
const fieldId = (name) => data.customFields.find(f => f.name.trim().toLowerCase().startsWith(name.toLowerCase()))?.id;

const F_CLIENT = data.customFields.find(f => f.name.trim() === 'Client')?.id;
const F_DATE_STAGED = data.customFields.find(f => f.name.trim() === 'Date Staged')?.id;
const F_DATE_DESTAGED = data.customFields.find(f => f.name.trim() === 'Date Destaged')?.id;
const F_AMOUNT = data.customFields.find(f => f.name.trim() === 'Amount Paid')?.id;
const F_LOCKBOX = fieldId('lockbox');
const F_INVOICED = data.customFields.find(f => f.name.trim() === 'Sent Invoice?')?.id;

const clients = new Map(); // name -> { name, email, phone }
const stages = [];
const stats = { skippedClosed: 0, skippedWrongList: 0, kept: 0 };

for (const c of data.cards) {
  if (c.closed) { stats.skippedClosed++; continue; }
  const list = listsById[c.idList];
  const listName = list?.name?.trim();
  const status = LIST_TO_STATUS[listName];
  if (!status) { stats.skippedWrongList++; continue; }

  const cf = c.customFieldItems || [];
  const get = (id) => cf.find(x => x.idCustomField === id);
  const clientName = get(F_CLIENT)?.value?.text?.trim();
  const dateStaged = get(F_DATE_STAGED)?.value?.date;
  const dateDestaged = get(F_DATE_DESTAGED)?.value?.date;
  const amount = get(F_AMOUNT)?.value?.number;
  const lockbox = get(F_LOCKBOX)?.value?.text?.trim();
  const invoiced = get(F_INVOICED)?.value?.checked === 'true';

  // Fallback: extract a leading client from "Client - Address" titles when
  // the custom field is empty.
  let resolvedClient = clientName;
  if (!resolvedClient) {
    const m = (c.name || '').match(/^([^—\-–]+?)\s*[—\-–]\s*(.+)$/);
    if (m) resolvedClient = m[1].trim();
  }
  if (!resolvedClient) resolvedClient = 'Imported — Unknown';

  if (!clients.has(resolvedClient)) {
    clients.set(resolvedClient, { name: resolvedClient });
  }

  // stage_date fallback to card creation date (objectId-encoded timestamp)
  let stageDate = dateStaged ? dateStaged.slice(0, 10) : null;
  if (!stageDate && c.id) {
    // Trello card IDs are MongoDB ObjectIds: first 8 hex chars = unix seconds
    const tsHex = c.id.slice(0, 8);
    const ts = parseInt(tsHex, 16);
    if (Number.isFinite(ts) && ts > 0) {
      stageDate = new Date(ts * 1000).toISOString().slice(0, 10);
    }
  }

  stages.push({
    trelloId: c.id,
    clientName: resolvedClient,
    address: (c.name || '').trim() || '(no address)',
    notes: (c.desc || '').trim() || null,
    status,
    stageDate,
    destageDate: dateDestaged ? dateDestaged.slice(0, 10) : null,
    amount: amount ?? 0,
    lockbox,
    invoiced,
  });
  stats.kept++;
}

// Emit SQL
const lines = [];
lines.push('-- Trello board import. Re-runnable.');
lines.push('-- Generated by scripts/build-trello-import-sql.mjs');
lines.push('begin;');

// Insert clients (idempotent on (name, imported_from='trello'))
lines.push('-- Clients');
for (const c of clients.values()) {
  lines.push(`insert into public.clients (name, imported_from) values (${sqlString(c.name)}, 'trello') on conflict do nothing;`);
}

// Stages — one INSERT per card, with subquery to look up the client by name+imported_from.
// Idempotent via the unique index on trello_card_id.
lines.push('-- Stages');
for (const s of stages) {
  lines.push(
    `insert into public.stages (client_id, address, status, stage_date, destage_date, amount, lockbox_code, notes, trello_card_id) ` +
    `select c.id, ${sqlString(s.address)}, ${sqlString(s.status)}, ${sqlDate(s.stageDate)}, ${sqlDate(s.destageDate)}, ${sqlNumber(s.amount)}, ${sqlString(s.lockbox)}, ${sqlString(s.notes)}, ${sqlString(s.trelloId)} ` +
    `from public.clients c where c.name = ${sqlString(s.clientName)} and c.imported_from = 'trello' ` +
    `on conflict (trello_card_id) where trello_card_id is not null do nothing;`
  );
}

lines.push('commit;');
fs.writeFileSync(OUT, lines.join('\n'));
console.error('Stats:', JSON.stringify(stats, null, 2));
console.error('Unique clients:', clients.size);
console.error('Stages emitted:', stages.length);
console.error('Wrote:', OUT, '(' + Math.round(fs.statSync(OUT).size / 1024) + ' KB)');
